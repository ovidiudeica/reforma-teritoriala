import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=n=>JSON.parse(readFileSync(new URL(n,import.meta.url),"utf8"));
const tops=[read("grigoriopol-2025-top.json"),read("grigoriopol-2026-top.json")];
const mid=[1,2,3,4,5].map(n=>read("grigoriopol-nested-0"+n+".json"));
const extra=read("grigoriopol-third-level.json");
const s=read("local-inventory-summary.json");
const laws=read("originals-14-recovery-status.json");
const parent=read("../ni-adm13-20261024/originals-18.json");
const direct=tops.flatMap(t=>t.rows.flatMap(r=>r.items));
const nested=mid.flatMap(t=>t.rows);
const items=[...direct,...nested.flatMap(r=>r.items),...extra.children];
const dirs=items.filter(x=>x.mime_type==="application/vnd.google-apps.folder");
const files=items.filter(x=>x.mime_type!=="application/vnd.google-apps.folder");
assert.deepEqual([tops[0].rows.length,tops[1].rows.length,nested.length,extra.children.length],[14,14,61,12]);
assert.deepEqual([direct.length,items.length,dirs.length,files.length],[151,369,62,307]);
assert.equal(new Set(files.map(x=>x.id||x.file_id)).size,307);
assert.equal(s.unique_files,307);
assert.equal(laws.rows.length,14);
assert.deepEqual(new Set(laws.rows.map(x=>x.publication_id)),new Set(parent.rows.filter(x=>!x.primary_original).map(x=>x.publication_id)));
assert.ok(laws.rows.every(x=>!x.authentic_issuer_original_recovered && x.effective_date_certified===false));
assert.equal(s.P9_1,"BLOCKED");
assert.equal(s.protected_ACTUAL_unchanged,true);
console.log("PASS 369 local metadata entries, 307 file IDs; 14 central originals remain blocked");
