import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateOsmRolesCatalog} from '../../atlas-osm-roles.mjs';
import {validateConsolidatedHierarchy} from '../../atlas-hierarchy-validate.mjs';
import {createNistreniaOperationalView,nistreniaSearchEntities,NISTR_EN_ROOT} from '../../atlas-nistrenia-jurisdiction.mjs';
import {createUrlConfig,normalizeUrlState,serializeUrlState,parseUrlState} from '../../atlas-url-state.mjs';
import {createGeometryFilterIndex} from '../../geometry-taxonomy.mjs';
const read=path=>JSON.parse(readFileSync(path,'utf8'));
const index=read('public/data/actual-entities.json');
const manifest=read('data/current/actual-release-manifest.json');
const tree=read('public/data/actual-consolidated-tree.json');
const catalog=read('public/data/p909-nistrenia-osm-navigation.json');
const byId=new Map(index.entities.map(e=>[e.id,e]));
const roles=validateOsmRolesCatalog(read('public/data/p907216-osm-roles.json'),byId,{snapshotId:manifest.snapshot_id,releaseFingerprint:manifest.release_fingerprint_sha256});
const official=validateConsolidatedHierarchy(tree,byId,{expectedCount:5848});
const make=()=>createNistreniaOperationalView({catalog,roles,entityById:byId,officialNodes:official,officialRoots:tree.root_ids});

test('P9.0.9.4 exactly 3 UI jurisdictions, 7 geometric groups and 85 aliases without a new ACTUAL polygon',()=>{
 const view=make();
 assert.equal(index.entity_count,5848);
 assert.equal(official.size,5848);
 assert.equal(view.nodes.size,5941);
 assert.deepEqual(view.rootIds,[...tree.root_ids,NISTR_EN_ROOT]);
 assert.equal(view.nodes.get(NISTR_EN_ROOT).display_name,'Nistrenia');
 assert.equal(view.nodes.get(NISTR_EN_ROOT).view_only,true);
 assert.equal(view.groupIds.length,7);
 assert.equal(view.toActual.size,85);
 assert.equal(view.roleIds.size,85);
 assert.deepEqual(new Set(view.toActual.values()),new Set(roles.keys()));
 assert.deepEqual(view.aggregates.get(NISTR_EN_ROOT).length,85);
 assert(view.groupIds.every(group=>view.nodes.get(group).parent_id===NISTR_EN_ROOT));
 assert([...view.toActual.entries()].every(([alias,actual])=>view.nodes.get(alias).source_actual_id===actual&&official.has(actual)));
 assert.equal(view.operationalJurisdiction('osm-r9581354'),'NI');
 assert.equal(view.operationalJurisdiction(tree.root_ids[1]),'MD');
 assert.equal(view.nodes.get(NISTR_EN_ROOT).child_ids.length,7);
 assert.equal(official.has(NISTR_EN_ROOT),false);
 assert.equal(byId.has(NISTR_EN_ROOT),false);
 assert.equal(catalog.root_has_actual_geometry,false);
 assert.equal(catalog.root_is_legal_jurisdiction,false);
 assert.equal(catalog.p91_import_allowed,false);
 assert.equal(catalog.actual_mutation_allowed,false);
 assert.equal(catalog.legal_semantic_acceptance,'BLOCKED_INCOMPLETE');
 assert.deepEqual(view.aggregates.get('view-nistrenia-group-osm-r944727').length,4);
 assert(view.roleIds.has('osm-r12463379')&&view.roleIds.has('osm-r9581354'),'Bender homonyms stay distinct');
});
test('P9.0.9.4 search indexes third operational group without changing legal ACTUAL entities',()=>{
 const view=make();
 const search=nistreniaSearchEntities(view,byId);
 assert.equal(search.length,93);
 assert.equal(search[0].display_name,'Nistrenia');
 assert.equal(search[0].jurisdiction,'NI');
 assert.equal(search.filter(e=>e.jurisdiction==='NI').length,93);
 assert.equal(new Set(search.map(x=>x.id)).size,93);
 assert(search.some(x=>x.searchable_names.includes('Transnistria')));
 assert.equal(index.entities.find(e=>e.id==='osm-r9581354').jurisdiction,'MD');
 assert.equal(official.get('osm-r9581354').jurisdiction,'MD');
 assert.equal(byId.size,5848);
});
test('P9.0.9.4 NI URL filter is independent and survives sharing, old URL defaults unchanged',()=>{
 const view=make();
 const config=createUrlConfig({entityById:byId,nodeById:view.nodes,rootIds:tree.root_ids,filterIndex:createGeometryFilterIndex(index.entities)});
 const initial=parseUrlState('',config);
 assert.deepEqual(initial.jurisdictions,['MD','RO']);
 assert.equal(serializeUrlState(initial,config),'');
 const niOnly=normalizeUrlState({...initial,jurisdictions:['NI'],openIds:[NISTR_EN_ROOT],visibleEntityIds:[...tree.root_ids,'osm-r9581354']},config);
 const encoded=serializeUrlState(niOnly,config);
 assert(encoded.includes('j=NI'));
 assert(encoded.includes('view-nistrenia'));
 assert.deepEqual(parseUrlState(encoded,config),niOnly);
 assert.deepEqual(parseUrlState('v=1&j=XX',config).jurisdictions,['MD','RO']);
 assert.equal(parseUrlState('v=1&j=NI',config).jurisdictions[0],'NI');
});
test('P9.0.9.4 corrupted or duplicated geometric aliases fail closed',()=>{
 assert.throws(()=>createNistreniaOperationalView({catalog:{...catalog,p91_import_allowed:true},roles,entityById:byId,officialNodes:official,officialRoots:tree.root_ids}),/Nistrenia OSM/);
 const missing=new Map(roles);missing.delete(missing.keys().next().value);
 assert.throws(()=>createNistreniaOperationalView({catalog,roles:missing,entityById:byId,officialNodes:official,officialRoots:tree.root_ids}),/Nistrenia OSM/);
});

