import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {validateNistreniaOutlinePackage,niOutlineIds} from '../../atlas-nistrenia-outlines.mjs';
import {createUrlConfig,parseUrlState,serializeUrlState,normalizeUrlState} from '../../atlas-url-state.mjs';
import {createGeometryFilterIndex} from '../../geometry-taxonomy.mjs';
import {createNistreniaOperationalView} from '../../atlas-nistrenia-jurisdiction.mjs';
import {validateOsmRolesCatalog} from '../../atlas-osm-roles.mjs';
import {validateConsolidatedHierarchy} from '../../atlas-hierarchy-validate.mjs';
const raw=path=>readFileSync(path,'utf8'),read=path=>JSON.parse(raw(path));
const geo=read('public/data/p9095-osm-outlines.json'),proof=read('public/data/p9095-osm-outlines-manifest.json');
const nav=read('public/data/p909-nistrenia-osm-navigation.json');
const index=read('public/data/actual-entities.json'),tree=read('public/data/actual-consolidated-tree.json');
const manifest=read('data/current/actual-release-manifest.json');
const byId=new Map(index.entities.map(e=>[e.id,e]));
const roles=validateOsmRolesCatalog(read('public/data/p907216-osm-roles.json'),byId,{snapshotId:manifest.snapshot_id,releaseFingerprint:manifest.release_fingerprint_sha256});
const official=validateConsolidatedHierarchy(tree,byId,{expectedCount:5848});
const view=createNistreniaOperationalView({catalog:nav,roles,entityById:byId,officialNodes:official,officialRoots:tree.root_ids});
const sha=x=>createHash('sha256').update(x).digest('hex');

test('P9.0.9.5 eight individual source-only OSM outlines, no ACTUAL mutation or duplicate IDs',()=>{
 assert.equal(index.entity_count,5848);assert.equal(official.size,5848);
 assert.equal(sha(raw('public/data/p9095-osm-outlines.json')),proof.file_sha256);
 const map=validateNistreniaOutlinePackage(geo,proof,nav);
 assert.deepEqual([...map.keys()],niOutlineIds);
 assert.equal(map.size,8);assert.equal(view.roleIds.size,85);assert.equal(view.groupIds.length,7);
 assert(map.values().every(f=>f.properties.view_only&&!f.properties.legal_certified));
 assert(niOutlineIds.every(id=>!byId.has(id)&&!official.has(id)));
 assert.equal(proof.actual_catalog_untouched,true);assert.equal(proof.actual_geometry_untouched,true);
 assert.equal(proof.p91_import_allowed,false);assert.equal(geo.metadata.p91_import_allowed,false);
 assert.equal(read('docs/p9.0.4.3-promotion-policy.json').p91_import_allowed,false);
 assert.equal(read('docs/p9.0.4.3-promotion-policy.json').semantic_acceptance,'BLOCKED_INCOMPLETE');
});
test('P9.0.9.5 source bundle refuses missing/duplicate and uncertified features',()=>{
 const broken=structuredClone(geo);broken.features[0].geometry.coordinates=[];
 assert.throws(()=>validateNistreniaOutlinePackage(broken,proof,nav),/unverified relation/);
 const duplicate=structuredClone(geo);duplicate.features[1].id=duplicate.features[0].id;
 assert.throws(()=>validateNistreniaOutlinePackage(duplicate,proof,nav),/missing or duplicated/);
 const certified=structuredClone(geo);certified.features[0].properties.legal_certified=true;
 assert.throws(()=>validateNistreniaOutlinePackage(certified,proof,nav),/unverified relation/);
 const unrestricted=structuredClone(proof);unrestricted.p91_import_allowed=true;
 assert.throws(()=>validateNistreniaOutlinePackage(geo,unrestricted,nav),/untrusted source manifest/);
});
test('P9.0.9.5 URLs default to 3 outlines RO MD NI, while NI districts and 85 children stay off',()=>{
 const config=createUrlConfig({entityById:byId,nodeById:view.nodes,rootIds:tree.root_ids,treeRootIds:view.rootIds,operationalOutlineIds:niOutlineIds,filterIndex:createGeometryFilterIndex(index.entities)});
 const def=parseUrlState('',config);
 assert.deepEqual(def.jurisdictions,['MD','NI','RO']);
 assert.deepEqual(def.visibleEntityIds.slice().sort(),tree.root_ids.slice().sort());
 assert.deepEqual(def.visibleOperationalOutlineIds,['view-nistrenia']);
 assert.equal(def.openIds.length,3);
 assert.equal(serializeUrlState(def,config),'');
 const custom=normalizeUrlState({...def,visibleOperationalOutlineIds:['view-nistrenia-group-osm-r1702216'],jurisdictions:['NI'],visibleEntityIds:tree.root_ids},config);
 const encoded=serializeUrlState(custom,config);
 assert.match(encoded,/v=2/);assert.match(encoded,/o=view-nistrenia/);assert.match(encoded,/o=view-nistrenia-group-osm-r1702216/);
 assert.deepEqual(parseUrlState(encoded,config),custom);
 assert.deepEqual(parseUrlState('v=1',config).jurisdictions,['MD','RO']);
 assert.deepEqual(parseUrlState('v=1',config).visibleOperationalOutlineIds,[]);
 assert.deepEqual(parseUrlState('v=1&j=NI',config).jurisdictions,['NI']);
 assert.equal(parseUrlState('v=2&j=NI',config).visibleOperationalOutlineIds[0],'view-nistrenia');
});
